#!/usr/bin/env python3
"""base16 schemes -> src/styles/themes.css + src/data/themes.json

Every colour on the site comes from a semantic role below, and every role is
derived from the 16 base16 slots. Schemes differ in how they use the slots
(Rosé Pine's base0B is teal, Gruvbox light's base0A is a pale yellow), so each
role has a contrast floor; a slot that misses it is darkened (light schemes)
or lightened (dark schemes) until it passes, which keeps its hue. Run after adding a scheme:  python3 scripts/themes.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'scripts' / 'base16'

# family label, light slug, dark slug
FAMILIES = [
    ('Marginalia', 'marginalia-light', 'marginalia-dark'),
    ('Gruvbox', 'gruvbox-light-medium', 'gruvbox-dark-medium'),
    ('Rosé Pine', 'rose-pine-dawn', 'rose-pine'),
    ('Catppuccin', 'catppuccin-latte', 'catppuccin-mocha'),
    ('Everforest', 'everforest-light-medium', 'everforest-dark-medium'),
    ('Solarized', 'solarized-light', 'solarized-dark'),
    ('Tokyo Night', 'tokyo-night-light', 'tokyo-night-dark'),
    ('Nord', 'nord-light', 'nord'),
]

def load(slug):
    t = (SRC / f'{slug}.yaml').read_text()
    return {k: v.lower() for k, v in re.findall(r'(base0[0-9A-F]):\s*"(#[0-9a-fA-F]{6})"', t)}

def rgb(h): return [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
def hexc(c): return '#' + ''.join(f'{round(max(0, min(1, x)) * 255):02x}' for x in c)
def lum(h):
    return sum(w * (x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4) for w, x in zip((.2126, .7152, .0722), rgb(h)))
def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + .05) / (lb + .05)
def mix(a, b, t): return hexc([x + (y - x) * t for x, y in zip(rgb(a), rgb(b))])

def fit(col, toward, grounds, floor):
    """mix col toward `toward` until it clears `floor` on every ground"""
    for i in range(41):
        c = mix(col, toward, i / 40)
        if all(contrast(c, g) >= floor for g in grounds):
            return c, i
    return toward, 40

def roles(p):
    bg, panel = p['base00'], p['base01']
    dark = lum(bg) < .2
    extreme = '#ffffff' if dark else '#000000'
    fg, _ = fit(p['base05'], extreme, [bg, panel], 7)
    # base02 is a selection colour; in Solarized it is mid-grey, so code wells
    # and rules are derived from bg/fg instead of trusting it
    sunk = mix(panel, fg, .06 if dark else .045)
    grounds = [bg, panel, sunk]
    r, fixed = {}, []
    def role(name, slot, floor, toward=extreme, on=grounds):  # black/white keeps the hue; fg would grey it
        c, steps = fit(p[slot], toward, on, floor)
        if steps: fixed.append(f'{name}<-{slot}+{steps * 2.5:.0f}%')
        r[name] = c
    r.update(bg=bg, panel=panel, sunk=sunk, fg=fg)
    role('muted', 'base04', 4.5)
    role('faint', 'base03', 1.9 if dark else 2.3, on=[bg])  # trunks, ticks: graphics only; light paper needs a firmer line
    r['rule'], _ = fit(mix(bg, fg, .12 if dark else .15), fg, [bg, panel], 1.3 if dark else 1.4)
    for name, slot in [('accent', 'base0D'), ('nest', 'base0E'), ('live', 'base0B'), ('warn', 'base0A'),
                       ('danger', 'base08'), ('ember', 'base09'), ('cyan', 'base0C')]:
        role(name, slot, 4.5)
    r['on-accent'] = bg if contrast(bg, r['accent']) >= contrast(fg, r['accent']) else fg
    return r, fixed, dark

def block(p, r, dark):
    raw = ';'.join(f'--{k.replace("base", "b")}:{v}' for k, v in p.items())
    sem = ';'.join(f'--{k}:{v}' for k, v in r.items())
    return f'{raw};{sem};color-scheme:{"dark" if dark else "light"}'

css = ['/* generated by scripts/themes.py; do not edit */']
meta = []
for label, light, dark_slug in FAMILIES:
    fam = re.sub(r'[^a-z]+', '-', label.lower()).strip('-')
    entry = {'id': fam, 'label': label}
    for mode, slug in (('light', light), ('dark', dark_slug)):
        p = load(slug)
        r, fixed, dark = roles(p)
        assert dark == (mode == 'dark'), f'{slug} is not {mode}'
        sel = f':root[data-scheme="{fam}"][data-mode="{mode}"]'
        if fam == 'marginalia':
            # no-JS / first paint default
            if mode == 'light': sel = ':root,' + sel
            else: css.append(f'@media (prefers-color-scheme:dark){{:root:not([data-mode]){{{block(p, r, dark)}}}}}')
        css.append(f'{sel}{{{block(p, r, dark)}}}')
        entry[mode] = {'name': slug, 'swatch': [r['bg'], r['panel'], r['fg'], r['accent'], r['nest'], r['live'], r['ember']]}
        print(f'{slug:26} fg {contrast(r["fg"], p["base00"]):4.1f}  {" ".join(fixed) or "clean"}')
    meta.append(entry)

(ROOT / 'src/styles/themes.css').write_text('\n'.join(css) + '\n')
(ROOT / 'src/data/themes.json').write_text(json.dumps(meta, indent=1))
